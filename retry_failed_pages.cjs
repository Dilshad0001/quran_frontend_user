function download(page) {
  const url = `https://quran.ksu.edu.sa/png_big/${page}.png`;
  const filePath = `${outputDir}${page}.png`;

  https.get(url, (res) => {
    if (res.statusCode !== 200) {
      console.log(`❌ Still failed: ${page}`);
      return;
    }

    const file = fs.createWriteStream(filePath);
    res.pipe(file);

    file.on("finish", () => {
      file.close();
      console.log(`✔ RETRY DONE: ${page}`);
    });
  });
}

